def prune_stale():
    """Delete files a previous run generated that this run did not."""
    if not os.path.exists(MANIFEST):
        return
    try:
        old = set(json.load(io.open(MANIFEST, encoding="utf-8")).get("files", []))
    except (ValueError, KeyError):
        return
    for rel in sorted(old - set(written)):
        path = os.path.join(ROOT, rel)
        if os.path.exists(path):
            try:
                os.remove(path)
                print("  removed stale %s" % rel)
            except OSError as exc:
                print("  WARNING could not remove %s (%s)" % (rel, exc))


# Keys that are configuration or are consumed by another section, so their
# absence from section_order is expected rather than a mistake.
NOT_SECTIONS = {"basics", "section_order", "section_titles", "talks"}


def validate(data):
    """Catch the easy mistakes: a section written but never displayed, or listed
    but never written."""
    msgs = []
    order = list(data.get("section_order", []))

    for key in data:
        if key in NOT_SECTIONS or key in order:
            continue
        if key in ("invited_talks", "conference_presentations"):
            continue
        msgs.append(
            "'%s' exists in cv_source.yml but is NOT in section_order, so it will "
            "not appear anywhere. Add it to section_order to show it." % key)

    virtual = {"invited_talks", "conference_presentations"}
    for key in order:
        if key not in data and key not in virtual:
            msgs.append("section_order lists '%s', but there is no such key in "
                        "cv_source.yml. It will render empty." % key)

    todo = [t["slug"] for t in data.get("talks", [])
            if (t.get("title") or "").strip().lower() in ("todo", "tbd")]
    if todo:
        msgs.append(
            "%d of %d talks still have `title: TODO` and are rendering from the "
            "meeting name only. Fill them in (or delete the title line if the "
            "talk had no title): %s"
            % (len(todo), len(data.get("talks", [])), ", ".join(todo[:3])
               + (", ..." if len(todo) > 3 else "")))
    return msgs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", choices=["md", "collections", "tex"], action="append")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if any output differs from what is on disk")
    args = ap.parse_args()
    targets = args.only or ["md", "collections", "tex"]

    with io.open(SOURCE, encoding="utf-8") as fh:
        data = yaml.safe_load(fh)

    warnings = validate(data)

    if args.check:
        stale = []
        if "md" in targets:
            stale += _diff("_pages/cv.md", build_markdown(data))
        if "tex" in targets:
            stale += _diff("cv/cv.tex", build_tex(data))
        if stale:
            print("Out of date (run `make cv`):\n  " + "\n  ".join(stale))
            return 1
        print("CV outputs are up to date.")
        return 0

    if "md" in targets:
        write("_pages/cv.md", build_markdown(data))
    if "collections" in targets:
        build_collections(data)
    if "tex" in targets:
        write("cv/cv.tex", build_tex(data))

    if set(targets) == {"md", "collections", "tex"}:
        prune_stale()
        json.dump({"files": sorted(written)}, io.open(MANIFEST, "w", encoding="utf-8"), indent=1)

    print("Generated %d file(s) from _data/cv_source.yml" % len(written))
    for msg in warnings:
        print("  WARNING: %s" % msg)
    if _dropped_glyphs:
        print("  NOTE: character(s) %s cannot be typeset by pdflatex and were "
              "left out of the PDF. They still appear on the website."
              % " ".join(sorted(_dropped_glyphs)))
    return 0


def _diff(rel, content):
    path = os.path.join(ROOT, rel)
    if not os.path.exists(path):
        return [rel + " (missing)"]
    return [] if io.open(path, encoding="utf-8").read() == content else [rel]


if __name__ == "__main__":
    sys.exit(main())
