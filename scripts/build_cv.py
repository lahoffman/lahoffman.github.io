"""
build_cv.py -- generate the whole CV surface from one YAML file.

    _data/cv_source.yml
            |
            +--> _pages/cv.md            (website CV page)
            +--> _publications/*.md      (/publications/ collection)
            +--> _talks/*.md             (/talks/ collection)
            +--> _teaching/*.md          (/teaching/ collection)
            +--> cv/cv.tex               (moderncv source -> files/cv.pdf)

Every file listed above is OVERWRITTEN on each run. Do not hand-edit them.
Files generated by a previous run that are no longer in the YAML are deleted;
the list of what we generated lives in .cv-generated.json.

Usage:
    python3 scripts/build_cv.py                 # build everything
    python3 scripts/build_cv.py --check         # fail if output would change
    python3 scripts/build_cv.py --only tex      # md | collections | tex
"""

