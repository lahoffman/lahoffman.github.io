TEX_SECTION_TITLES = {
    "research_interests": "Research Interests",
    "education": "Education",
    "research_experience": "Research Experience",
    "industry_experience": "Industry Experience",
    "technical_expertise": "Technical Expertise",
    "publications": "Publications",
    "patents": "Patents",
    "invited_talks": "Invited Talks",
    "conference_presentations": "Conference Presentations, Workshops, and Seminars",
    "teaching": "Teaching Experience",
    "guest_lectures": "Guest Lectures",
    "mentorship": "Mentorship",
    "leadership": "Leadership",
    "service": "Service",
    "honors": "Honors and Awards",
    "activities": "Activities",
}

DEFAULT_PREAMBLE = r"""% Styling for the generated CV. Safe to edit by hand.
\documentclass[11pt,letterpaper,sans]{moderncv}

\moderncvstyle{classic}
\moderncvcolor{blue}

\usepackage[utf8]{inputenc}
\usepackage[scale=0.82]{geometry}
\setlength{\hintscolumnwidth}{3.2cm}
\setlength{\makecvtitlenamewidth}{10cm}

\usepackage{xurl}
\usepackage{enumitem}
\setlist[itemize]{leftmargin=*, itemsep=0.15em, topsep=0.15em}
"""


def tex_itemize(bullets):
    if not bullets:
        return "{}"
    lines = ["{%", r"\begin{itemize}"]
    for bl in bullets:
        lines.append(r"    \item %s" % tex_escape(norm_ws(bl)))
    lines += [r"\end{itemize}}"]
    return "\n".join(lines)


def cventry(dates, title, org, location, extra, bullets):
    return r"\cventry{%s}{%s}{%s}{%s}{%s}%s" % (
        tex_escape(dates), tex_escape(title), tex_escape(org),
        tex_escape(location), tex_escape(extra or ""), tex_itemize(bullets))


def build_tex(data):
    b = data["basics"]
    preamble_path = os.path.join(ROOT, "cv", "preamble.tex")
    if os.path.exists(preamble_path):
        preamble = io.open(preamble_path, encoding="utf-8").read()
    else:
        # Seeded once, then owned by the user -- deliberately NOT recorded in the
        # manifest, so it is never overwritten or pruned by later builds.
        preamble = DEFAULT_PREAMBLE
        os.makedirs(os.path.dirname(preamble_path), exist_ok=True)
        with io.open(preamble_path, "w", encoding="utf-8") as fh:
            fh.write(DEFAULT_PREAMBLE)
        print("  seeded cv/preamble.tex (edit this to change PDF styling)")

    L = [WARNING_TEX, preamble, ""]
    L.append(r"\firstname{%s}" % tex_escape(b["first_name"]))
    L.append(r"\familyname{%s}" % tex_escape(b["family_name"]))
    L.append(r"\email{%s}" % b["email"])
    if b.get("phone"):
        L.append(r"\phone[mobile]{%s}" % tex_escape(b["phone"]))
    if b.get("homepage"):
        L.append(r"\homepage{%s}" % b["homepage"])
    if b.get("github"):
        L.append(r"\social[github]{%s}" % b["github"])
    if b.get("orcid"):
        L.append(r"\social[orcid]{%s}" % b["orcid"])
    L += ["", r"\begin{document}", "", r"\makecvtitle", r"\vspace{-1.0em}", ""]

    def head(key):
        L.append(r"\section{%s}" % title_for(data, key, TEX_SECTION_TITLES, True))

    for key in data["section_order"]:
        if key in merged_sections(data):
            head(key)
            for e in merged_entries(data, key):
                hint, body = compact_line(e, "tex", separator(data), bold_roles(data))
                L.append(r"\cvitem{%s}{%s}" % (tex_escape(hint), body))

        elif key not in TEX_SECTION_TITLES and key not in talk_sections(data):
            # Unknown key -> render generically. No code change needed to add one.
            head(key)
            for hint, text in generic_items(data.get(key), "tex",
                                            separator(data), bold_roles(data)):
                L.append(r"\cvitem{%s}{%s}" % (tex_escape(hint), text))

        elif key == "research_interests":
            head(key)
            L.append(r"\cvitem{}{%s}" % tex_escape(norm_ws(data["research_interests"])))

        elif key == "education":
            head(key)
            for e in data["education"]:
                notes = " ".join(md_escape(n).rstrip(".") + "." for n in e.get("notes", []))
                L.append(r"\cventry{%s}{%s}{%s}{%s}{}{%s}" % (
                    tex_escape(e["date"]), tex_escape(e["degree"]),
                    tex_escape(e["institution"]), tex_escape(e["location"]),
                    tex_escape(notes)))

        elif key in ("research_experience", "industry_experience"):
            head(key)
            for j in data.get(key, []):
                L.append(cventry(j["dates"], j["title"], j["org"], j["location"],
                                 j.get("advisor"), j.get("bullets")))
                L.append("")

        elif key == "technical_expertise":
            head(key)
            for t in data["technical_expertise"]:
                L.append(r"\cvitem{%s}{%s}" % (tex_escape(t["label"]),
                                               tex_escape(norm_ws(t["text"]))))

        elif key == "publications":
            head(key)
            first, co = split_pubs(data)
            for label, group in (("First-Author Publications", first),
                                 ("Co-Author Publications", co)):
                if not group:
                    continue
                L.append(r"\subsection{%s}" % label)
                for p in group:
                    year = "In progress" if p.get("status") == "in_progress" else str(p["year"])
                    L.append(r"\cvitem{%s}{%s}" % (tex_escape(year), pub_reference(p, "tex", bold_names(data))))

        elif key == "patents":
            head(key)
            for p in data.get("patents", []):
                txt = tex_escape(norm_ws(p["text"]))
                if p.get("url"):
                    txt += r" \url{%s}." % p["url"]
                L.append(r"\cvitem{%s}{%s}" % (p["year"], txt))

        elif key in talk_sections(data):
            head(key)
            for t in talks_for_section(data, key):
                L.append(r"\cvitem{%s}{%s}" % (t["year"], talk_line(t, "tex")))

        elif key == "teaching":
            head(key)
            for t in compact_entries(data.get("teaching")):
                if is_compact(data.get("teaching")):
                    # Join first, escape once, so the pipe becomes \textbar{}.
                    body = "%s%s%s" % (t["title"], separator(data),
                                       t.get("summary") or t["org"])
                    L.append(r"\cvitem{%s}{%s}" % (tex_escape(t["dates"]),
                                                   tex_escape(norm_ws(body))))
                else:
                    L.append(cventry(t["dates"], t["title"], t["org"],
                                     t["location"], None, t.get("bullets")))
                    L.append("")

        elif key == "guest_lectures":
            head(key)
            for g in data.get("guest_lectures", []):
                L.append(r"\cvitem{%s}{%s. \textit{%s}. %s.}" % (
                    tex_escape(g["term"]), tex_escape(g["title"]),
                    tex_escape(g["course"]), tex_escape(g["org"])))

        elif key in ("mentorship", "leadership", "service"):
            head(key)
            for e in compact_entries(data.get(key)):
                hint, body = compact_line(e, "tex", separator(data), bold_roles(data))
                L.append(r"\cvitem{%s}{%s}" % (tex_escape(hint), body))

        elif key in ("honors", "activities"):
            head(key)
            for h in data.get(key, []):
                L.append(r"\cvitem{%s}{%s}" % (tex_escape(h["date"]),
                                               tex_escape(norm_ws(h["text"]))))

        L.append("")

    L.append(r"\end{document}")
    return "\n".join(L) + "\n"


