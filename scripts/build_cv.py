MD_SECTION_TITLES = {
    "research_interests": "Research interests",
    "education": "Education",
    "research_experience": "Research experience",
    "industry_experience": "Industry experience",
    "technical_expertise": "Technical expertise",
    "publications": "Publications",
    "patents": "Patents",
    "invited_talks": "Invited talks",
    "conference_presentations": "Conference presentations, workshops, and seminars",
    "teaching": "Teaching",
    "guest_lectures": "Guest lectures",
    "service": "Leadership, service, and mentorship",
    "honors": "Honors and awards",
    "activities": "Activities",
}


def md_entry(dates, title, org, location, extra=None, bullets=None):
    out = ["* %s: %s" % (md_escape(dates), md_escape(title))]
    where = ", ".join(x for x in [md_escape(org), md_escape(location)] if x)
    if where:
        out.append("  * %s" % where)
    if extra:
        out.append("  * %s" % md_escape(extra))
    for b in bullets or []:
        out.append("  * %s" % md_escape(b).rstrip("."))
    return "\n".join(out)


def build_markdown(data):
    b = data["basics"]
    L = [
        "---",
        "layout: archive",
        'title: "CV"',
        "permalink: /cv/",
        "author_profile: true",
        "redirect_from:",
        "  - /resume",
        "---",
        "",
        WARNING_MD,
        "",
        "{% include base_path %}",
        "",
        "[Download this CV as a PDF]({{ base_path }}/files/cv.pdf)",
        "",
    ]

    def head(key):
        L.extend([title_for(data, key, MD_SECTION_TITLES), "=" * 6])

    for key in data["section_order"]:
        if key not in MD_SECTION_TITLES:
            # Unknown key -> render generically. No code change needed to add one.
            head(key)
            for hint, text in generic_items(data.get(key)):
                L.append(("* %s: %s" % (md_escape(hint), md_escape(text)))
                         if hint else "* %s" % md_escape(text))
            L.append("")

        elif key == "research_interests":
            head(key)
            L.extend([md_escape(data["research_interests"]), ""])

        elif key == "education":
            head(key)
            for e in data["education"]:
                L.append("* %s, %s, %s" % (md_escape(e["degree"]), md_escape(e["institution"]), e["year"]))
                for n in e.get("notes", []):
                    L.append("  * %s" % md_escape(n))
            L.append("")

        elif key in ("research_experience", "industry_experience"):
            head(key)
            for j in data.get(key, []):
                L.append(md_entry(j["dates"], j["title"], j["org"], j["location"],
                                  j.get("advisor"), j.get("bullets")))
                L.append("")

        elif key == "technical_expertise":
            head(key)
            for t in data["technical_expertise"]:
                L.append("* %s: %s" % (md_escape(t["label"]), md_escape(t["text"]).rstrip(".")))
            L.append("")

        elif key == "publications":
            head(key)
            L.append("")
            first, co = split_pubs(data)
            for label, group in (("First-author publications", first),
                                 ("Co-author publications", co)):
                if not group:
                    continue
                L.extend([label, "-" * 6])
                for p in group:
                    year = "*In progress*" if p.get("status") == "in_progress" else str(p["year"])
                    L.append("* %s: %s" % (year, pub_reference(p, "md")))
                L.append("")

        elif key == "patents":
            head(key)
            for p in data.get("patents", []):
                line = "* %s: %s" % (p["year"], md_escape(p["text"]))
                if p.get("url"):
                    line += " [Link](%s)" % p["url"]
                L.append(line)
            L.append("")

        elif key in ("invited_talks", "conference_presentations"):
            head(key)
            invited, contributed = split_talks(data)
            for t in (invited if key == "invited_talks" else contributed):
                L.append("* %s: %s" % (t["year"], talk_line(t, "md")))
            L.append("")

        elif key == "teaching":
            head(key)
            for t in data.get("teaching", []):
                L.append(md_entry(t["dates"], t["title"], t["org"], t["location"],
                                  bullets=t.get("bullets")))
                L.append("")

        elif key == "guest_lectures":
            head(key)
            for g in data.get("guest_lectures", []):
                L.append("* %s: %s. *%s*. %s." % (
                    md_escape(g["term"]), md_escape(g["title"]),
                    md_escape(g["course"]), md_escape(g["org"])))
            L.append("")

        elif key == "service":
            head(key)
            s = data["service"]
            for r in s.get("roles", []):
                L.append("* %s: %s, %s" % (md_escape(r["dates"]), md_escape(r["title"]), md_escape(r["org"])))
                for bl in r.get("bullets", []):
                    L.append("  * %s" % md_escape(bl).rstrip("."))
            for it in s.get("items", []):
                L.append("* %s: %s" % (md_escape(it["label"]), md_escape(it["text"])))
            if s.get("mentorship"):
                L.append("* Mentorship:")
                for m in s["mentorship"]:
                    L.append("  * %s" % md_escape(m).rstrip("."))
            L.append("")

        elif key in ("honors", "activities"):
            head(key)
            for h in data.get(key, []):
                L.append("* %s: %s" % (md_escape(h["date"]), md_escape(h["text"])))
            L.append("")

    return "\n".join(L).rstrip() + "\n"


# ---------------------------------------------------------- collections ------
def yaml_str(s):
    """Quote a string safely for a YAML front-matter scalar."""
    return '"%s"' % md_escape(s).replace("\\", "\\\\").replace('"', '\\"')


def build_collections(data):
    # --- publications ---
    for p in data.get("publications", []):
        if p.get("site") is False or p.get("status") == "in_progress":
            continue
        citation = "%s (%s). &quot;%s&quot; <i>%s</i>%s." % (
            p["authors"], p["year"], p["title"], p["venue"],
            ", " + p["details"] if p.get("details") else "")
        body = ""
        if p.get("doi"):
            body = "\n[Read the paper](%s)\n" % doi_url(p["doi"])
        fm = [
            "---",
            "title: %s" % yaml_str(p["title"]),
            "collection: publications",
            "category: manuscripts",
            "permalink: /publication/%s-%s" % (p["date"], p["slug"]),
            "excerpt: %s" % yaml_str(p.get("excerpt", "")),
            "date: %s" % p["date"],
            "venue: %s" % yaml_str(p["venue"]),
        ]
        if p.get("doi"):
            fm.append("paperurl: %s" % yaml_str(doi_url(p["doi"])))
        fm += ["citation: %s" % yaml_str(citation), "---", "", WARNING_MD, body]
        write("_publications/%s-%s.md" % (p["date"], p["slug"]), "\n".join(fm))

    # --- talks ---
    for t in data.get("talks", []):
        if t.get("site") is False:
            continue
        # Page heading is the talk's own title once known; until then the
        # meeting name stands in, so the page is never headed "TODO".
        title = talk_title(t)
        meeting = t.get("meeting") or t.get("title")
        fm = [
            "---",
            "title: %s" % yaml_str(title or meeting),
            "collection: talks",
            "type: %s" % yaml_str(t.get("format") or t.get("type", "Talk")),
            "permalink: /talks/%s" % t["slug"],
            "venue: %s" % yaml_str(meeting or t.get("venue", "")),
            "date: %s" % t["date"],
            "location: %s" % yaml_str(t["location"]),
            "---",
            "",
            WARNING_MD,
            "",
        ]
        if title and meeting:
            fm.append("Presented at %s." % md_escape(meeting))
            fm.append("")
        write("_talks/%s.md" % t["slug"], "\n".join(fm))

    # --- teaching (courses + guest lectures both live here) ---
    for t in data.get("teaching", []):
        body = "\n".join("- %s" % md_escape(b) for b in t.get("bullets", []))
        fm = [
            "---",
            "title: %s" % yaml_str(t["title"]),
            "collection: teaching",
            "type: %s" % yaml_str(t.get("type", "Course")),
            "permalink: /teaching/%s" % t["slug"],
            "venue: %s" % yaml_str(t["org"]),
            "date: %s" % t["date"],
            "location: %s" % yaml_str(t["location"]),
            "---",
            "",
            WARNING_MD,
            "",
            md_escape(t["dates"]) + ".",
            "",
            body,
            "",
        ]
        write("_teaching/%s.md" % t["slug"], "\n".join(fm))

    for g in data.get("guest_lectures", []):
        fm = [
            "---",
            "title: %s" % yaml_str("Guest lecture: " + g["title"]),
            "collection: teaching",
            'type: "Guest lecture"',
            "permalink: /teaching/%s" % g["slug"],
            "venue: %s" % yaml_str("%s, %s" % (g["org"], g["course"])),
            "date: %s" % g["date"],
            "location: %s" % yaml_str(g["location"]),
            "---",
            "",
            WARNING_MD,
            "",
            "%s." % md_escape(g["term"]),
            "",
            "Guest lecture delivered in the course *%s*." % md_escape(g["course"]),
            "",
        ]
        write("_teaching/%s.md" % g["slug"], "\n".join(fm))


