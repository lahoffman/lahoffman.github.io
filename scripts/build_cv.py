# ----------------------------------------------------------- date display ----
# Display dates as MM/YYYY. Seasons and terms carry no month, so they collapse
# to the bare year, per the rule "if month is not provided just use YYYY".
# Set `date_style: words` in cv_source.yml to keep the original wording.
MONTHS = {"jan": "01", "feb": "02", "mar": "03", "apr": "04", "may": "05",
          "jun": "06", "jul": "07", "aug": "08", "sep": "09", "sept": "09",
          "oct": "10", "nov": "11", "dec": "12"}
SEASONS = ("Fall", "Autumn", "Winter", "Spring", "Summer")
MONTH_RE = r"(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Sept|Oct|Nov|Dec)[a-z]*\.?"
ISO_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


def format_date_hint(text):
    """'Oct. 2023' -> '10/2023';  'Mar.-Jun. 2020' -> '03/2020-06/2020';
       'Fall 2024-Spring 2025' -> '2024-2025';  '2011-2016' -> unchanged."""
    if text is None:
        return text
    out = str(text)
    if ISO_RE.match(out.strip()):        # Jekyll's own date field -- leave alone
        return out

    # "Mar.-Jun. 2020" -- two months sharing one trailing year.
    def pair(m):
        a, b, year = MONTHS[m.group(1).lower()], MONTHS[m.group(2).lower()], m.group(3)
        return "%s/%s\u2013%s/%s" % (a, year, b, year)
    out = re.sub(MONTH_RE + r"\s*[\u2013\u2014-]\s*" + MONTH_RE + r"\s+(\d{4})",
                 pair, out)

    # "Oct. 2023" -> "10/2023"
    out = re.sub(MONTH_RE + r"\s+(\d{4})",
                 lambda m: "%s/%s" % (MONTHS[m.group(1).lower()], m.group(2)), out)

    # Seasons and terms have no month: drop the word, keep the year.
    for word in SEASONS:
        out = re.sub(r"\b%s\s+(?=\d{4})" % word, "", out)
    return re.sub(r"\s+", " ", out).strip()


def normalise_dates(node, enabled=True):
    """Rewrite every display-date field in the loaded YAML, in place."""
    if not enabled:
        return node
    if isinstance(node, dict):
        for k, v in node.items():
            if k in ("dates", "term", "date") and isinstance(v, str):
                node[k] = format_date_hint(v)
            else:
                normalise_dates(v)
    elif isinstance(node, list):
        for item in node:
            normalise_dates(item)
    return node


# ---------------------------------------------------------------- helpers ----
def write(path, content):
    """Write UTF-8 text, creating parent dirs, and record it in the manifest."""
    full = path if os.path.isabs(path) else os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with io.open(full, "w", encoding="utf-8") as fh:
        fh.write(content)
    written.append(os.path.relpath(full, ROOT))


# Characters pdflatex + inputenc can typeset: ASCII, Latin-1 Supplement and
# Latin Extended-A (accents), plus the punctuation we actually use. Anything
# else -- emoji, symbols, CJK -- is dropped from the PDF with a warning, but is
# kept on the website, where the browser handles it fine.
TEX_EXTRA_OK = "\u2010\u2011\u2012\u2013\u2014\u2018\u2019\u201c\u201d\u2026\u2032\u2033\u00b0\n\t"


def _tex_ok(ch):
    cp = ord(ch)
    return (0x20 <= cp <= 0x7E          # ASCII printable
            or 0xA0 <= cp <= 0x17F      # Latin-1 Supplement + Latin Extended-A
            or ch in TEX_EXTRA_OK)


_dropped_glyphs = set()


def tex_safe(s):
    """Drop glyphs pdflatex cannot render, remembering them for a warning."""
    kept = []
    for ch in s:
        if _tex_ok(ch):
            kept.append(ch)
        else:
            _dropped_glyphs.add(ch)
    return re.sub(r"[ ]+", " ", "".join(kept)).strip()


def tex_escape(s):
    """Escape LaTeX specials. Leaves accented UTF-8 characters alone."""
    if s is None:
        return ""
    s = tex_safe(str(s))
    for a, b in (
        ("\\", r"\textbackslash{}"),
        ("&", r"\&"),
        ("%", r"\%"),
        ("$", r"\$"),
        ("#", r"\#"),
        ("_", r"\_"),
        ("{", r"\{"),
        ("}", r"\}"),
        ("~", r"\textasciitilde{}"),
        ("^", r"\textasciicircum{}"),
        ("|", r"\textbar{}"),   # a bare | renders as an em dash in TeX
    ):
        s = s.replace(a, b)
    s = s.replace("–", "--").replace("—", "---")
    s = s.replace("“", "``").replace("”", "''")
    s = s.replace("‘", "`").replace("’", "'")
    # Straight double quotes -> LaTeX open/close pairs
    parts = s.split('"')
    if len(parts) > 1:
        out, opening = parts[0], True
        for p in parts[1:]:
            out += ("``" if opening else "''") + p
            opening = not opening
        s = out
    return s


# This site runs kramdown with `input: GFM`, whose table detection fires on ANY
# line containing a pipe -- no header row needed. A literal "|" anywhere in the
# CV therefore renders as a stray one-cell table. Emitting the numeric entity
# instead sidesteps table detection entirely (which scans raw text) while still
# displaying a real pipe, because `entity_output: as_char` converts it back.
MD_PIPE = "&#124;"


def norm_ws(s):
    """Collapse whitespace. Format-neutral -- safe before either escaper."""
    if s is None:
        return ""
    return re.sub(r"\s+", " ", str(s)).strip()


def md_escape(s):
    """Whitespace + neutralise pipes so kramdown sees no tables. MARKDOWN ONLY.

    Never feed the result to tex_escape: the entity's '#' would be escaped and
    the PDF would print a literal "&#124;".
    """
    return norm_ws(s).replace("|", MD_PIPE)


def emph_md(s):
    return "*%s*" % s


def emph_tex(s):
    return r"\textit{%s}" % s


def doi_url(doi):
    return "https://doi.org/%s" % doi


def pub_tail(p, fmt):
    """Shared trailing text of a publication reference: venue, details, DOI."""
    esc = tex_escape if fmt == "tex" else md_escape
    emph = emph_tex if fmt == "tex" else emph_md
    bits = []
    if p.get("venue"):
        bits.append(emph(esc(p["venue"])))
    if p.get("details"):
        bits.append(esc(p["details"]))
    tail = ", ".join(bits)
    if p.get("doi"):
        if fmt == "tex":
            tail += ". DOI: %s" % tex_escape(p["doi"])
        else:
            tail += ". [DOI: %s](%s)" % (md_escape(p["doi"]), doi_url(p["doi"]))
    return tail


DEFAULT_BOLD_NAMES = ["Hoffman, L.", "L. Hoffman"]


def bold_names(data):
    """Names to embolden in author lists; override with `basics.bold_name:`."""
    configured = (data.get("basics") or {}).get("bold_name")
    if not configured:
        return DEFAULT_BOLD_NAMES
    return configured if isinstance(configured, list) else [configured]


def bold_own_name(authors, fmt, names):
    """Wrap the CV owner's name in bold wherever it appears in an author list."""
    # Longest first, so "Hoffman, L." wins over a bare "Hoffman".
    for name in sorted(names, key=len, reverse=True):
        marked = ("**%s**" % name) if fmt == "md" else (r"\textbf{%s}" % name)
        if name in authors and marked not in authors:
            authors = authors.replace(name, marked)
            break
    return authors


def pub_reference(p, fmt, names=None):
    esc = tex_escape if fmt == "tex" else md_escape
    # Escape first, then bold, so the bold markup itself is never escaped.
    authors = bold_own_name(esc(p["authors"]), fmt, names or DEFAULT_BOLD_NAMES)
    ref = "%s %s" % (authors, esc(p["title"]))
    tail = pub_tail(p, fmt)
    return ref + (" " + tail if tail else "")


TODO_MARKERS = ("", "todo", "tbd", "none")


def talk_title(t):
    """The talk's own title, or None if it has none / is still a placeholder."""
    title = (t.get("title") or "").strip()
    return None if title.lower() in TODO_MARKERS else title


def talk_line(t, fmt):
    """
    'Title of the talk.' Meeting name. Location. Format.

    With no title yet, degrades to exactly the old form: Meeting. Location.
    Format. -- so partially-filled data always reads correctly.
    """
    esc = tex_escape if fmt == "tex" else md_escape
    bits = [esc(x) for x in (t.get("meeting") or t.get("title"),
                             t.get("location"), t.get("format")) if x]
    line = ". ".join(bits) + "."

    title = talk_title(t)
    if not title:
        return line
    clean = title.rstrip(".")
    quoted = ('"%s."' % md_escape(clean) if fmt == "md"
              else "``%s.''" % tex_escape(clean))
    return quoted + " " + line


def split_pubs(data):
    pubs = data.get("publications", [])
    first = [p for p in pubs if p.get("authorship", "first") == "first"]
    co = [p for p in pubs if p.get("authorship") == "co"]
    # In-progress first, then newest to oldest by date.
    key = lambda p: (0 if p.get("status") == "in_progress" else 1,
                     _desc(str(p.get("date", p.get("year", "")))))
    return sorted(first, key=key), sorted(co, key=key)


DEFAULT_TALK_SECTIONS = {"invited_talks": "invited",
                         "conference_presentations": "contributed"}


def talk_sections(data):
    return data.get("talk_sections") or DEFAULT_TALK_SECTIONS


def talks_for_section(data, section_key):
    """Talks whose `group:` maps to this section, newest first."""
    group = talk_sections(data).get(section_key)
    if group is None:
        return []
    known = set(talk_sections(data).values())
    picked = [t for t in data.get("talks", [])
              # An unrecognised group falls into the last section rather than
              # vanishing silently.
              if t.get("group") == group
              or (t.get("group") not in known
                  and group == list(talk_sections(data).values())[-1])]
    return sorted(picked, key=lambda t: _desc(str(t.get("date", ""))))


def _desc(s):
    """Sort key that orders strings in reverse (newest date first)."""
    return tuple(-ord(c) for c in s)


SMALL_WORDS = {"and", "or", "of", "for", "the", "a", "an", "in", "on", "to", "with"}


def titleize(key, title_case=False):
    """personal_interests -> 'Personal interests', or 'Personal Interests'."""
    words = key.replace("_", " ").split()
    if not title_case:
        return " ".join(words).capitalize()
    return " ".join(w.capitalize() if i == 0 or w not in SMALL_WORDS else w
                    for i, w in enumerate(words))


def title_for(data, key, table, title_case=False):
    """Heading: explicit `section_titles:` override, then built-in, then derived."""
    custom = (data.get("section_titles") or {}).get(key)
    return custom or table.get(key) or titleize(key, title_case)


def generic_items(value, fmt="md", sep=None, bold=True):
    """
    Normalise an unrecognised section into (hint, text) pairs, so ANY new key
    added to cv_source.yml renders without touching this file. Shapes accepted:

        key: a paragraph of prose                        -> one unhinted line
        key: [plain string, plain string]                -> unhinted bullets
        key: [{date|dates|label|term: .., text: ..}]      -> hinted bullets
        key: {compact: true, entries: [...]}             -> compact one-liners
    """
    sep = DEFAULT_SEPARATOR if sep is None else sep
    if value is None:
        return []
    if isinstance(value, str):
        return [("", md_escape(value) if fmt == "md" else tex_escape(value))]
    items = []
    for entry in compact_entries(value):        # unwraps {compact:, entries:}
        if isinstance(entry, str):
            items.append(("", md_escape(entry) if fmt == "md" else tex_escape(entry)))
        elif isinstance(entry, dict):
            items.append(compact_line(entry, fmt, sep, bold))
    return items


DEFAULT_SEPARATOR = "; "


def bold_roles(data):
    """Bold the position title in compact entries. `bold_roles: false` to stop."""
    return data.get("bold_roles", True)


def separator(data):
    """Separator between parts of a compact entry. `compact_separator:` in YAML."""
    return data.get("compact_separator", DEFAULT_SEPARATOR)


def compact_line(e, fmt="md", sep=DEFAULT_SEPARATOR, bold=True):
    """
    One-line entry, Gregory-style:  Who, Role | Org  -- or Label: text.
    Assembled from whichever of these keys are present.
    """
    esc = md_escape if fmt == "md" else tex_escape
    hint = e.get("dates") or e.get("date") or ""

    if e.get("label") and e.get("text"):
        return e["label"], esc(e["text"])

    # The position title is emphasised; everything else is plain. Bolding is
    # applied AFTER escaping, so the markup itself is never escaped.
    role = esc(e["role"]) if e.get("role") else ""
    if role and bold:
        role = ("**%s**" % role) if fmt == "md" else (r"\textbf{%s}" % role)
    left = ", ".join(x for x in (esc(e["who"]) if e.get("who") else "", role) if x)
    right = sep.join(esc(x) for x in (e.get("org"), e.get("note"), e.get("text")) if x)
    return hint, sep.join(x for x in (left, right) if x)


def compact_entries(value):
    """A section written as {compact: true, entries: [...]} -> list of entries."""
    if isinstance(value, dict):
        return value.get("entries", [])
    return value or []


def is_compact(value):
    return isinstance(value, dict) and value.get("compact", True)


def merged_sections(data):
    """{display_key: [source_key, ...]} -- render several data blocks as one."""
    return data.get("merged_sections") or {}


def merged_members(data):
    out = set()
    for sources in merged_sections(data).values():
        out.update(sources)
    return out


def as_compact(source_key, e):
    """Map a source section's entry shape onto the compact {role, text} shape,
    so different kinds of entry can share one merged section."""
    if source_key == "teaching":
        # `role` is the bolded position; `title` is kept for the /teaching/ page.
        return {"dates": e.get("dates"),
                "role": e.get("role") or e.get("title"),
                "text": e.get("summary") or e.get("org")}
    if source_key == "guest_lectures":
        return {"dates": e.get("term"),
                "role": e.get("role") or "Guest Lecturer",
                "text": "; ".join(x for x in (e.get("title"), e.get("course"),
                                              e.get("org")) if x)}
    return e          # already a compact entry


def merged_entries(data, key):
    """Every entry of a merged section, in source order."""
    items = []
    for src in merged_sections(data).get(key, []):
        for e in compact_entries(data.get(src)):
            items.append(as_compact(src, e))
    return items


# ------------------------------------------------------------ markdown CV ----
MD_SECTION_TITLES = {
    "research_interests": "Research interests",
    "education": "Education",
    "research_experience": "Research experience",
    "industry_experience": "Industry experience",
    "technical_expertise": "Technical expertise",
    "publications": "Publications",
    "patents": "Patents",
    "invited_talks": "Invited talks",
    "conference_presentations": "Conference presentations, workshops, and seminars",
    "teaching": "Teaching",
    "guest_lectures": "Guest lectures",
    "mentorship": "Mentorship",
    "leadership": "Leadership",
    "service": "Service",
    "honors": "Honors and awards",
    "activities": "Activities",
}


def md_entry(dates, title, org, location, extra=None, bullets=None):
    out = ["* %s: %s" % (md_escape(dates), md_escape(title))]
    where = ", ".join(x for x in [md_escape(org), md_escape(location)] if x)
    if where:
        out.append("  * %s" % where)
    if extra:
        out.append("  * %s" % md_escape(extra))
    for b in bullets or []:
        out.append("  * %s" % md_escape(b).rstrip("."))
    return "\n".join(out)


def build_markdown(data):
    b = data["basics"]
    L = [
        "---",
        "layout: archive",
        'title: "CV"',
        "permalink: /cv/",
        "author_profile: true",
        "redirect_from:",
        "  - /resume",
        "---",
        "",
        WARNING_MD,
        "",
        "{% include base_path %}",
        "",
        "[Download this CV as a PDF]({{ base_path }}/files/cv.pdf)",
        "",
    ]

    def head(key):
        L.extend([title_for(data, key, MD_SECTION_TITLES), "=" * 6])

    for key in data["section_order"]:
        if key in merged_sections(data):
            head(key)
            for e in merged_entries(data, key):
                hint, body = compact_line(e, "md", separator(data), bold_roles(data))
                L.append("* %s: %s" % (md_escape(hint), body) if hint
                         else "* %s" % body)
            L.append("")

        elif key not in MD_SECTION_TITLES and key not in talk_sections(data):
            # Unknown key -> render generically. No code change needed to add one.
            head(key)
            for hint, text in generic_items(data.get(key), "md", separator(data), bold_roles(data)):
                L.append(("* %s: %s" % (md_escape(hint), text))
                         if hint else "* %s" % text)
            L.append("")

        elif key == "research_interests":
            head(key)
            L.extend([md_escape(data["research_interests"]), ""])

        elif key == "education":
            head(key)
            for e in data["education"]:
                L.append("* %s, %s, %s" % (md_escape(e["degree"]), md_escape(e["institution"]), e["year"]))
                for n in e.get("notes", []):
                    L.append("  * %s" % md_escape(n))
            L.append("")

        elif key in ("research_experience", "industry_experience"):
            head(key)
            for j in data.get(key, []):
                L.append(md_entry(j["dates"], j["title"], j["org"], j["location"],
                                  j.get("advisor"), j.get("bullets")))
                L.append("")

        elif key == "technical_expertise":
            head(key)
            for t in data["technical_expertise"]:
                L.append("* %s: %s" % (md_escape(t["label"]), md_escape(t["text"]).rstrip(".")))
            L.append("")

        elif key == "publications":
            head(key)
            L.append("")
            first, co = split_pubs(data)
            for label, group in (("First-author publications", first),
                                 ("Co-author publications", co)):
                if not group:
                    continue
                L.extend([label, "-" * 6])
                for p in group:
                    year = "*In progress*" if p.get("status") == "in_progress" else str(p["year"])
                    L.append("* %s: %s" % (year, pub_reference(p, "md", bold_names(data))))
                L.append("")

        elif key == "patents":
            head(key)
            for p in data.get("patents", []):
                line = "* %s: %s" % (p["year"], md_escape(p["text"]))
                if p.get("url"):
                    line += " [Link](%s)" % p["url"]
                L.append(line)
            L.append("")

        elif key in talk_sections(data):
            head(key)
            for t in talks_for_section(data, key):
                L.append("* %s: %s" % (t["year"], talk_line(t, "md")))
            L.append("")

        elif key == "teaching":
            head(key)
            for t in compact_entries(data.get("teaching")):
                if is_compact(data.get("teaching")):
                    L.append("* %s: %s%s%s" % (
                        md_escape(t["dates"]), md_escape(t["title"]),
                        separator(data), md_escape(t.get("summary") or t["org"])))
                else:
                    L.append(md_entry(t["dates"], t["title"], t["org"],
                                      t["location"], bullets=t.get("bullets")))
                    L.append("")
            L.append("")

        elif key == "guest_lectures":
            head(key)
            for g in data.get("guest_lectures", []):
                L.append("* %s: %s. *%s*. %s." % (
                    md_escape(g["term"]), md_escape(g["title"]),
                    md_escape(g["course"]), md_escape(g["org"])))
            L.append("")

        elif key in ("mentorship", "leadership", "service"):
            head(key)
            for e in compact_entries(data.get(key)):
                hint, body = compact_line(e, "md", separator(data), bold_roles(data))
                L.append("* %s: %s" % (md_escape(hint), body) if hint
                         else "* %s" % body)
            L.append("")

        elif key in ("honors", "activities"):
            head(key)
            for h in data.get(key, []):
                L.append("* %s: %s" % (md_escape(h["date"]), md_escape(h["text"])))
            L.append("")

    return "\n".join(L).rstrip() + "\n"


